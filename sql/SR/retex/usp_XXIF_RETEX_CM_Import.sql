-- 一個 DOC_ID（一次 RETEX API 批次）在 JSON_DOC 中可能含多筆 DocNo，
-- IFACE.STATUS 是 DOC_ID 層級的單一欄位，無法同時表示「批次內部分成功、部分失敗」，
-- 因此採「整批全部產生 PURTC 才算完成」原則：只要批次內有任一 DocNo 未成功，
-- 整批一律轉 STATUS='E' 待人工確認，避免部分失敗被誤標記為完成、或誤蓋掉已成功的標記。
-- 先用 CROSS APPLY 逐筆算出是否命中 @PURTC_TMP，再依 DOC_ID 彙總，
-- 避免直接對含 EXISTS 子查詢的運算式做 COUNT() 導致 Msg 130。
INSERT INTO @DOC_STATUS (DOC_ID, FULLY_MATCHED)
SELECT h.DOC_ID,
       CASE WHEN COUNT(*) = SUM(m.is_matched) THEN 1 ELSE 0 END
FROM @XX_DOC_HEADERS h
	CROSS APPLY (
		SELECT CASE WHEN EXISTS (SELECT 'X' FROM @PURTC_TMP p WHERE p.TC009 = h.DocNo) THEN 1 ELSE 0 END AS is_matched
	) m
GROUP BY h.DOC_ID;

UPDATE IFACE
	SET STATUS         = N'5',
	    PROCESSED_DATE = SYSUTCDATETIME()
WHERE DOC_ID IN (SELECT DOC_ID FROM @DOC_STATUS WHERE FULLY_MATCHED = 1);

-- 找不到供應商對照 (XX_SUPPLIERS/PURMA) 或單別設定 (CMSMQ)，批次內至少一筆 DocNo 未產生採購單者，整批轉錯誤待人工處理
