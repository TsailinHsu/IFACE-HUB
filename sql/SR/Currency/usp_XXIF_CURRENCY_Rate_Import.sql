USE IFACE_SR
GO

IF OBJECT_ID ( 'XXIF_CURRENCY_Rate_Import', 'P' ) IS NOT NULL   
    DROP PROCEDURE XXIF_CURRENCY_Rate_Import;  

GO  

CREATE PROCEDURE XXIF_CURRENCY_Rate_Import  
AS

/*
	XXIF_CURRENCY_Rate_Import 匯率匯入
	來源 currencyAPI (currencyapi.com)
	Daily HKD/SGD/MYR/CNY to USD RATE

	維護 Cosmos ERP MRB(CNY) 匯率表

	2023/05/25 修正美金精度小數後四位

	v1.1 2023/10/13 變更 CREATOR 為 API (原 T0031)
*/

DECLARE @COMPANY NVARCHAR(20)
DECLARE @CREATOR NVARCHAR(10)
DECLARE @CREATE_DATE NVARCHAR(8)
DECLARE @CREATE_TIME NVARCHAR(8)

SET @COMPANY = 'SR'
SET @CREATOR = 'API'
SET @CREATE_DATE = CONVERT(VARCHAR, GETDATE(), 112)
SET @CREATE_TIME = CONVERT(VARCHAR, GETDATE(), 108)
DECLARE @ErrMsg		NVARCHAR(2000)

DECLARE @RATE TABLE
(
	APP_FUNCTION	NVARCHAR(255),
	APP_MODULE		NVARCHAR(255),
	DOC_ID			NVARCHAR(255), 
	BATCH_ID		NVARCHAR(255), 
	STATUS			NVARCHAR(255), 
	RATE_DATE		NVARCHAR(8),
	RATE_CODE		NVARCHAR(3),		
	RATE			NUMERIC(18, 6)
)
;

BEGIN TRY

WITH XX_RATE AS (
	SELECT 
		APP_FUNCTION,
		APP_MODULE,
		DOC_ID, 
		BATCH_ID, 
		STATUS,
		META,
		HKD,
		SGD,
		MYR,
		TWD,
		CNY
	FROM IFACE	
		CROSS APPLY
		OPENJSON (JSON_DOC, '$') WITH (
			META	NVARCHAR(MAX)	'$.meta' AS JSON,
			HKD		NVARCHAR(MAX)	'$.data.HKD' AS JSON,
			SGD		NVARCHAR(MAX)	'$.data.SGD' AS JSON,
			MYR		NVARCHAR(MAX)	'$.data.MYR' AS JSON,
			TWD		NVARCHAR(MAX)	'$.data.TWD' AS JSON,
			CNY		NVARCHAR(MAX)	'$.data.CNY' AS JSON
		)
	WHERE 1=1 
		AND STATUS = '0'
		AND APP_MODULE = N'currencyAPI'
		AND APP_FUNCTION = N'RATE'
)

INSERT INTO @RATE (
	APP_FUNCTION,
	APP_MODULE,
	DOC_ID, 
	BATCH_ID, 
	STATUS,
	RATE_DATE,
	RATE_CODE,
	RATE 
	)
SELECT 
	APP_FUNCTION,
	APP_MODULE,
	DOC_ID, 
	BATCH_ID, 
	STATUS,
	CONVERT(VARCHAR, RATE_DATE, 112),
	RATE_CODE,
	RATE
FROM XX_RATE
	CROSS APPLY (SELECT * FROM OPENJSON (META) WITH (
		RATE_DATE	DATE	'$.last_updated_at'
	)) m
	CROSS APPLY (SELECT * FROM OPENJSON (HKD) WITH (
		RATE_CODE	NVARCHAR(3)		'$.code',
		RATE		NUMERIC(18,6)	'$.value'
	)) hkd
UNION ALL
SELECT 
	APP_FUNCTION,
		APP_MODULE,
		DOC_ID, 
		BATCH_ID, 
		STATUS,
		CONVERT(VARCHAR, RATE_DATE, 112),
		RATE_CODE,
		RATE
FROM XX_RATE
	CROSS APPLY (SELECT * FROM OPENJSON (META) WITH (
		RATE_DATE	DATE	'$.last_updated_at'
	)) m
	CROSS APPLY (SELECT * FROM OPENJSON (SGD) WITH (
		RATE_CODE	NVARCHAR(3)		'$.code',
		RATE		NUMERIC(18,6)	'$.value'
	)) sgd
UNION ALL
SELECT 
	APP_FUNCTION,
		APP_MODULE,
		DOC_ID, 
		BATCH_ID, 
		STATUS,
		CONVERT(VARCHAR, RATE_DATE, 112),
		RATE_CODE,
		RATE
FROM XX_RATE
	CROSS APPLY (SELECT * FROM OPENJSON (META) WITH (
		RATE_DATE	DATE	'$.last_updated_at'
	)) m
	CROSS APPLY (SELECT * FROM OPENJSON (MYR) WITH (
		RATE_CODE	NVARCHAR(3)		'$.code',
		RATE		NUMERIC(18,6)	'$.value'
	)) myr
UNION ALL
SELECT 
	APP_FUNCTION,
		APP_MODULE,
		DOC_ID, 
		BATCH_ID, 
		STATUS,
		CONVERT(VARCHAR, RATE_DATE, 112),
		RATE_CODE,
		RATE
FROM XX_RATE
	CROSS APPLY (SELECT * FROM OPENJSON (META) WITH (
		RATE_DATE	DATE	'$.last_updated_at'
	)) m
	CROSS APPLY (SELECT * FROM OPENJSON (TWD) WITH (
		RATE_CODE	NVARCHAR(3)		'$.code',
		RATE		NUMERIC(18,6)	'$.value'
	)) twd
UNION ALL
SELECT 
	APP_FUNCTION,
		APP_MODULE,
		DOC_ID, 
		BATCH_ID, 
		STATUS,
		CONVERT(VARCHAR, RATE_DATE, 112),
		RATE_CODE,
		RATE
FROM XX_RATE
	CROSS APPLY (SELECT * FROM OPENJSON (META) WITH (
		RATE_DATE	DATE	'$.last_updated_at'
	)) m
	CROSS APPLY (SELECT * FROM OPENJSON (CNY) WITH (
		RATE_CODE	NVARCHAR(3)		'$.code',
		RATE		NUMERIC(18,6)	'$.value'
	)) cny

;

BEGIN TRANSACTION;

INSERT INTO XX_TO_USD_RATE (RATE_CODE, RATE_DATE, RATE)
SELECT 
	RATE_CODE, RATE_DATE, 1/RATE
FROM @RATE r
	WHERE NOT EXISTS (SELECT 'X' FROM XX_TO_USD_RATE x WHERE x.RATE_CODE = r.RATE_CODE AND x.RATE_DATE = r.RATE_DATE);

-- Cosmos ERP, RMB/USD 每日對台幣匯率
-- CMSMG 幣別匯率檔單身
-- ACTNP 總帳幣別匯率單身檔 

-- 人民幣匯率
INSERT INTO SR..CMSMG ( 
	COMPANY, CREATOR, USR_GROUP, CREATE_DATE, CREATE_TIME, MODIFIER, MODI_DATE, MODI_TIME, FLAG, TRANS_TYPE, TRANS_NAME, DataGroup,
	MG001, MG002, 
	MG003, MG004, MG005, MG006, MG007, 
	MG008, MG009, MG010, MG011, MG012, MG013, MG014, MG015, MG016, MG017
	)

SELECT @COMPANY, @CREATOR, N'000', @CREATE_DATE, @CREATE_TIME, @CREATOR, @CREATE_DATE, @CREATE_TIME, N'1', N'P001', N'CMSI06', N'000',
	N'RMB', CNY.RATE_DATE, 
	ROUND(TWD.RATE / CNY.RATE, 4), ROUND(TWD.RATE / CNY.RATE, 4), ROUND(TWD.RATE / CNY.RATE, 4), ROUND(TWD.RATE / CNY.RATE, 4),
	0.000000, 0.000000, N'', N'', N'', N'', 0.000000, N'', N'', N'', 0.000000
FROM @RATE CNY 
	INNER JOIN @RATE TWD ON TWD.RATE_CODE = N'TWD'
 WHERE CNY.RATE_CODE = N'CNY'
	AND NOT EXISTS (SELECT 'X' FROM SR..CMSMG WHERE MG001 = N'RMB' AND MG002 = CNY.RATE_DATE)
;

-- 美金匯率
INSERT INTO SR..CMSMG ( 
	COMPANY, CREATOR, USR_GROUP, CREATE_DATE, CREATE_TIME, MODIFIER, MODI_DATE, MODI_TIME, FLAG, TRANS_TYPE, TRANS_NAME, DataGroup,
	MG001, MG002, MG003, MG004, MG005, MG006, MG007, 
	MG008, MG009, MG010, MG011, MG012, MG013, MG014, MG015, MG016, MG017
	)

SELECT @COMPANY, @CREATOR, N'000', @CREATE_DATE, @CREATE_TIME, @CREATOR, @CREATE_DATE, @CREATE_TIME, N'1', N'P001', N'CMSI06', N'000',
	N'USD', RATE_DATE, ROUND(RATE, 4) , ROUND(RATE, 4) , ROUND(RATE, 4), ROUND(RATE, 4) ,
	0.000000, 0.000000, N'', N'', N'', N'', 0.000000, N'', N'', N'', 0.000000
FROM @RATE  
 WHERE RATE_CODE = N'TWD'
	AND NOT EXISTS (SELECT 'X' FROM SR..CMSMG WHERE MG001 = N'USD' AND MG002 = RATE_DATE);

-- 
INSERT INTO SR..ACTNP ( 
	COMPANY, CREATOR, USR_GROUP, CREATE_DATE, CREATE_TIME, MODIFIER, MODI_DATE, MODI_TIME, FLAG, TRANS_TYPE, TRANS_NAME, DataGroup,
	NP001, NP002, NP003, NP004, NP005, NP006, NP007, NP008, NP009, NP010, NP011, NP012, NP013, NP014, NP015, NP016, NP017, NP018
	)
SELECT 
	COMPANY, CREATOR, USR_GROUP, CREATE_DATE, CREATE_TIME, MODIFIER, MODI_DATE, MODI_TIME, FLAG, TRANS_TYPE, TRANS_NAME, DataGroup,
	MG001, N'NTD', MG002, MG003, MG004, MG005, MG006, MG007, MG008, MG009, MG010, MG011, MG012, MG013, MG014, MG015, MG016, MG017
FROM SR..CMSMG 
WHERE CREATE_DATE = @CREATE_DATE AND CREATOR = @CREATOR
	AND NOT EXISTS (SELECT 'X' FROM SR..ACTNP WHERE NP001 = MG001 AND NP002 = N'NTD' AND NP003 = MG002)
;

UPDATE IFACE
	SET STATUS = N'5'
WHERE DOC_ID IN (SELECT DISTINCT DOC_ID FROM @RATE);

COMMIT TRANSACTION;

END TRY
BEGIN CATCH

	SET @ErrMsg = LEFT(ERROR_MESSAGE(), 2000);

	IF XACT_STATE() <> 0
		ROLLBACK TRANSACTION;

	UPDATE IFACE
		SET STATUS        = N'E',
		    ERROR_MESSAGE = @ErrMsg,
		    RETRY_COUNT   = RETRY_COUNT + 1
	WHERE DOC_ID IN (SELECT DOC_ID FROM @RATE);

	INSERT INTO IFACE_ERROR (
		ORIGINAL_DOC_ID, BATCH_ID, CREATION_DATE, API, APP_MODULE, APP_FUNCTION,
		QUERY_PARAMS, JSON_DOC, MERCHANT, ERROR_MESSAGE, RETRY_COUNT
	)
	SELECT
		DOC_ID, BATCH_ID, CREATION_DATE, API, APP_MODULE, APP_FUNCTION,
		QUERY_PARAMS, JSON_DOC, MERCHANT, @ErrMsg, RETRY_COUNT
	FROM IFACE
	WHERE DOC_ID IN (SELECT DOC_ID FROM @RATE);

	THROW;

END CATCH