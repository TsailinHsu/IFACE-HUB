CREATE OR ALTER VIEW INVMB_EIP_APPLY_vw 
AS

WITH XX_INVMB AS (
	SELECT
		ID,
		GLOBAL_ID
	FROM IFACE
		CROSS APPLY
		OPENJSON (JSON_DOC, '$.data') WITH 
			(
				ID				NUMERIC			'$.id',
				GLOBAL_ID		NVARCHAR(255)	'$.global_id'
			)
	WHERE 1=1  AND STATUS = '5'
		AND APP_MODULE = N'EIP'
		AND APP_FUNCTION = N'preProducts'
)

SELECT ID,  GLOBAL_ID RefId 
FROM XX_INVMB
WHERE EXISTS (SELECT 'X' FROM SR..INVMB WHERE MB028 = GLOBAL_ID)
;