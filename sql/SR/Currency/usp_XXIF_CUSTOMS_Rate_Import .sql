USE IFACE_SR
GO

IF OBJECT_ID ( 'XXIF_CUSTOMS_Rate_Import', 'P' ) IS NOT NULL   
    DROP PROCEDURE XXIF_CUSTOMS_Rate_Import ;  

GO  

CREATE PROCEDURE XXIF_CUSTOMS_Rate_Import   
AS

/*
	海關三旬匯率匯入
*/


DECLARE @RATE TABLE
(
	APP_FUNCTION	NVARCHAR(255),
	DOC_ID			NVARCHAR(255), 
	BATCH_ID		NVARCHAR(255), 
	STATUS			NVARCHAR(255), 
	S_DATE			NVARCHAR(8),
	E_DATE			NVARCHAR(8),
	ITEMS			NVARCHAR(MAX)
)

DECLARE @ErrMsg		NVARCHAR(2000)

BEGIN TRY

INSERT INTO @RATE (
	APP_FUNCTION,
	DOC_ID, 
	BATCH_ID, 
	STATUS, 
	S_DATE,
	E_DATE,
	ITEMS
)
SELECT 
	APP_FUNCTION,
	DOC_ID, 
	BATCH_ID, 
	STATUS, 
	S_DATE,
	E_DATE,
	ITEMS
FROM IFACE
    CROSS APPLY
	OPENJSON (JSON_DOC, '$') WITH (
		S_DATE	NVARCHAR(8)	'$.start',
		E_DATE	NVARCHAR(8)	'$.end',
		ITEMS	NVARCHAR(MAX) '$.items' AS JSON
	)
WHERE 1=1 
	AND STATUS = '0'
	AND APP_MODULE = N'CUSTOMS'
	AND APP_FUNCTION = N'RATE'
;

INSERT INTO XX_CUSTOMS_RATE (
	START_DATE,
	END_DATE,
	CODE,
	BUY_RATE,
	SELL_RATE
)
SELECT 
	S_DATE,
	E_DATE,
	CODE,
	BUY_RATE,
	SELL_RATE
FROM @RATE
CROSS APPLY (SELECT * FROM OPENJSON (ITEMS) WITH (
		CODE		NVARCHAR(3)		'$.code',
		BUY_RATE	NUMERIC(18,5)	'$.buyValue',
		SELL_RATE	NUMERIC(18,5)	'$.sellValue'
	)) AS l
WHERE CODE IN (N'USD', N'CNY')
	AND NOT EXISTS (SELECT 'X' FROM XX_CUSTOMS_RATE x WHERE x.START_DATE = S_DATE AND x.END_DATE = E_DATE  AND x.CODE = l.CODE)
;

UPDATE IFACE 
	SET STATUS = N'5'
WHERE DOC_ID IN (SELECT DISTINCT DOC_ID FROM @RATE);

END TRY
BEGIN CATCH

	SET @ErrMsg = LEFT(ERROR_MESSAGE(), 2000);

	UPDATE IFACE
		SET STATUS        = N'E',
		    ERROR_MESSAGE = @ErrMsg,
		    RETRY_COUNT   = RETRY_COUNT + 1
	WHERE DOC_ID IN (SELECT DOC_ID FROM @RATE);

	INSERT INTO IFACE_ERROR (
		ORIGINAL_DOC_ID, BATCH_ID, CREATION_DATE, API, APP_MODULE, APP_FUNCTION,
		QUERY_PARAMS, JSON_DOC, MERCHANT, ERROR_MESSAGE, RETRY_COUNT
	)
	SELECT
		DOC_ID, BATCH_ID, CREATION_DATE, API, APP_MODULE, APP_FUNCTION,
		QUERY_PARAMS, JSON_DOC, MERCHANT, @ErrMsg, RETRY_COUNT
	FROM IFACE
	WHERE DOC_ID IN (SELECT DOC_ID FROM @RATE);

	THROW;

END CATCH