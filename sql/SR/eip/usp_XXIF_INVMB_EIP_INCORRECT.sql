USE IFACE_SR
GO

IF OBJECT_ID ( 'XXIF_INVMB_EIP_INCORRECT', 'P' ) IS NOT NULL   
    DROP PROCEDURE XXIF_INVMB_EIP_INCORRECT;  

GO  

CREATE PROCEDURE XXIF_INVMB_EIP_INCORRECT  
AS
/*

  根據 EIP 要求, 修正品號基本資料

  v1.1 2024/07/01 移除支援老彭友股份有限公司

*/

DECLARE @IFACE TABLE (
	APP_FUNCTION	NVARCHAR(100),
	DOC_ID			INT, 
	BATCH_ID		NVARCHAR(50), 
	STATUS			NVARCHAR(1), 
	ID				NUMERIC,
	TITLE			NVARCHAR(255),
	CODE			NVARCHAR(255),
	CODE_2			NVARCHAR(255),
	BARCODE			NVARCHAR(255),
	BRAND_CODE		NVARCHAR(255),
	PRODUCT_TYPE_KEY	NVARCHAR(255),
	PRODUCT_TYPE_TEXT	NVARCHAR(255),
	M_PRODUCT_TYPE_KEY	NVARCHAR(255),
	M_PRODUCT_TYPE_TEXT	NVARCHAR(255),
	BRAND_TITLE		NVARCHAR(255),
	M_BRAND_CODE	NVARCHAR(255),
	M_BRAND_TITLE	NVARCHAR(255),
	GROUP_CODE		NVARCHAR(255),
	GROUP_TITLE		NVARCHAR(255),
	M_GROUP_CODE	NVARCHAR(255),
	M_GROUP_TITLE	NVARCHAR(255),
	CATEGORY_CODE	NVARCHAR(255),
	CATEGORY_TITLE	NVARCHAR(255),
	M_CATEGORY_CODE	NVARCHAR(255),
	M_CATEGORY_TITLE	NVARCHAR(255)

)

INSERT INTO @IFACE (
	APP_FUNCTION,
	DOC_ID, 
	BATCH_ID, 
	STATUS, 
	ID,
	TITLE,
	CODE,
	CODE_2,
	BARCODE,
	PRODUCT_TYPE_KEY,
	PRODUCT_TYPE_TEXT,
	M_PRODUCT_TYPE_KEY,
	M_PRODUCT_TYPE_TEXT,
	BRAND_CODE,
	BRAND_TITLE,
	M_BRAND_CODE,
	M_BRAND_TITLE,
	GROUP_CODE,
	GROUP_TITLE,
	M_GROUP_CODE,
	M_GROUP_TITLE,
	CATEGORY_CODE,
	CATEGORY_TITLE,
	M_CATEGORY_CODE,
	M_CATEGORY_TITLE

)
SELECT
	APP_FUNCTION,
	DOC_ID, 
	BATCH_ID, 
	STATUS, 
	ID,
	TITLE,
	CODE,
	CODE_2,
	BARCODE,
	PRODUCT_TYPE_KEY,
	PRODUCT_TYPE_TEXT,
	M_PRODUCT_TYPE_KEY,
	M_PRODUCT_TYPE_TEXT,
	BRAND_CODE,
	BRAND_TITLE,
	M_BRAND_CODE,
	M_BRAND_TITLE,
	GROUP_CODE,
	GROUP_TITLE,
	M_GROUP_CODE,
	M_GROUP_TITLE,
	CATEGORY_CODE,
	CATEGORY_TITLE,
	M_CATEGORY_CODE,
	M_CATEGORY_TITLE
FROM IFACE
	CROSS APPLY
	OPENJSON (JSON_DOC, '$.data') WITH 
		(
			ID					NUMERIC			'$.id',
			TITLE				NVARCHAR(255)	'$.title',
			CODE				NVARCHAR(255)	'$.code',
			CODE_2				NVARCHAR(255)	'$.code_2',
			BARCODE				NVARCHAR(255)	'$.barcode',
			PRODUCT_TYPE_KEY	NVARCHAR(255)	'$.product_type.key',
			PRODUCT_TYPE_TEXT	NVARCHAR(255)	'$.product_type.text',
			M_PRODUCT_TYPE_KEY	NVARCHAR(255)	'$.manual_product_type.key',
			M_PRODUCT_TYPE_TEXT	NVARCHAR(255)	'$.manual_product_type.text',
			BRAND_CODE			NVARCHAR(255)	'$.brand.code',
			BRAND_TITLE			NVARCHAR(255)	'$.brand.title',
			M_BRAND_CODE		NVARCHAR(255)	'$.manual_brand.code',
			M_BRAND_TITLE		NVARCHAR(255)	'$.manual_brand.title',
			GROUP_CODE			NVARCHAR(255)	'$.group.code',
			GROUP_TITLE			NVARCHAR(255)	'$.group.title',
			M_GROUP_CODE		NVARCHAR(255)	'$.manual_group.code',
			M_GROUP_TITLE		NVARCHAR(255)	'$.manual_group.title',
			CATEGORY_CODE		NVARCHAR(255)	'$.category.code',
			CATEGORY_TITLE		NVARCHAR(255)	'$.category.title',
			M_CATEGORY_CODE		NVARCHAR(255)	'$.manual_category.code',
			M_CATEGORY_TITLE	NVARCHAR(255)	'$.manual_category.title'
		)
WHERE 1=1  AND STATUS = N'0'
	AND APP_MODULE = N'EIP'
	AND APP_FUNCTION = N'INVINC'
;

UPDATE I
	SET I.MB006 = ISNULL(C.MA002, MB006),
		I.MB008 = ISNULL(D.MA002, MB008),
		I.MB111 = ISNULL(E.MA002, MB111),
		I.MB005 = ISNULL(A.MA002, MB005),
		I.MODI_DATE = CONVERT(VARCHAR, GETDATE(), 112),
		I.MODI_TIME = CONVERT(VARCHAR, GETDATE(), 108),
		I.MODIFIER = N'API'
FROM SR..INVMB I
	INNER JOIN @IFACE ON CODE = MB001
	LEFT JOIN SR..INVMA C ON C.MA001 = N'2' AND C.MA002 = M_BRAND_CODE
	LEFT JOIN SR..INVMA D ON D.MA001 = N'4' AND D.MA002 = M_GROUP_CODE
	LEFT JOIN SR..INVMA E ON E.MA001 = N'5' AND E.MA002 = M_CATEGORY_CODE
	LEFT JOIN SR..INVMA A ON A.MA001 = N'1' AND A.MA003 = M_PRODUCT_TYPE_TEXT
;


UPDATE IFACE 
	SET STATUS = N'5' 
WHERE DOC_ID IN (SELECT DOC_ID FROM @IFACE);