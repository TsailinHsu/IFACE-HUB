CREATE OR ALTER VIEW COPTI_EIP_Reject_APPLY_vw 
AS

WITH XX_ORDER AS (
	SELECT
		ID,
		ORDER_ID
	FROM IFACE
		CROSS APPLY
		OPENJSON (JSON_DOC, '$.data') WITH 
			(
				ID				NUMERIC			'$.id',
				ORDER_ID		NVARCHAR(255)	'$.order.global_order_id'
			)
	WHERE 1=1 
		AND STATUS = '5'
		AND APP_MODULE = N'EIP'
		AND APP_FUNCTION = N'orderReject'
)


SELECT ID, CONCAT_WS ( '-', RTRIM (TI001), RTRIM (TI002)) RefId 
FROM XX_ORDER
	INNER JOIN SR..COPTI ON TI023 = ORDER_ID
;
