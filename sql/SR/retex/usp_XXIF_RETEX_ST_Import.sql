	DOC_ID,
	DocNo,
	CASE DenNo WHEN N'M01001' THEN N'CM' ELSE SUBSTRING(DocNo, 1, PATINDEX('%-%',DocNo)-1) END,
	CASE DenNo WHEN N'M01001' THEN DocNo ELSE SUBSTRING(DocNo, PATINDEX('%-%',DocNo)+1, LEN(DocNo)) END,
