GO


SET ANSI_NULLS ON
GO

SET QUOTED_IDENTIFIER ON
GO


CREATE   VIEW [dbo].[COPTG_SaaS_APPLY_vw] 
AS

WITH XX_APPLY_ID AS (
SELECT ID
FROM IFACE
    CROSS APPLY
	OPENJSON (JSON_DOC, '$.data') WITH 
		(
			ID	NUMERIC	'$.id'
		)
WHERE 1=1 
	AND STATUS = '5'
	AND APP_FUNCTION = N'SaaS' -- IN (N'平台費',  N'儲值')
)

SELECT 
	CONCAT_WS ( '-', RTRIM (TG001), RTRIM (TG002)) RefId, 
	TG020 URL, 
	CONVERT(INT, COPTG.TG027) ID
FROM SR..COPTG 
	INNER JOIN XX_APPLY_ID ON ID = CONVERT(INT, COPTG.TG027) 
WHERE TG028 = N'一頁商店' 
;
GO


