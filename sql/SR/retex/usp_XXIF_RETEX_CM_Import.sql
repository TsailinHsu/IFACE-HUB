	v1.3 2025/02/26 新增排除對象 A118 群豐欣業

	v2.1 2026/07/28 新增排除對象 A119 (BOXFUL倉, 作業模式與 A118 相同)

	v2.2 2026/07/28 修正 BUG：STATUS='5' 更新範圍原本涵蓋所有通過初始篩選的單據，
		未檢查是否真的通過 XX_SUPPLIERS/PURMA/CMSMQ 等 INNER JOIN 產生 PURTC/PURTD，
		導致供應商對照未設定時單據被誤標記為已完成、實際未產生採購單。
		現改為僅將實際寫入 @PURTC_TMP 的單據標記 STATUS='5'，其餘轉 STATUS='E' 並寫入 IFACE_ERROR。

	v2.3 2026/07/28 修正 BUG：IFACE 寫入端（transactions API）無重複匯入檢查，
		若同一區間重跑 cm_import，同一張 POS 單會在 IFACE 產生多筆 STATUS='0' 記錄，
		各自通過 NOT EXISTS(PURTC) 判斷（該判斷僅檢查已存在的 PURTC，無法阻擋同批次內的重複），
		導致同一張單被重複轉成兩張採購單。現於篩選後僅保留每個 DocNo 最早的 DOC_ID 繼續處理，
		重複者僅寫入 IFACE_ERROR 稽核紀錄並排除，不直接改 IFACE.STATUS。

	v2.4 2026/07/28 修正 BUG：一個 DOC_ID（一次 RETEX API 批次）在 JSON_DOC 中可能包含多筆 DocNo，
		但 IFACE.STATUS 是 DOC_ID 層級的單一欄位。v2.2 的寫法以「是否存在於 @PURTC_TMP」逐筆 DocNo 判斷，
		若同一 DOC_ID 內部分 DocNo 成功、部分失敗，STATUS='5' 與 STATUS='E' 兩段 UPDATE 會同時命中
		同一個 DOC_ID，後執行者覆蓋前者，導致結果不可預期（可能整批被誤標記完成，或已成功的部分被覆蓋為錯誤）。
		現改為以 DOC_ID 為單位彙總判斷：批次內所有 DocNo 都成功產生 PURTC 才整批標記 STATUS='5'，
		只要有一筆未成功，整批一律標記 STATUS='E' 待人工確認，確保狀態值與 PURTC 實際結果一致。
		（實作上先以 @DOC_STATUS 暫存表用 CROSS APPLY 逐筆算出比對結果再彙總，
		避免直接對含 EXISTS 子查詢的運算式呼叫 COUNT() 觸發 Msg 130。）

	v2.0 2026/01/01 起併入光速火箭, 
		採購單價格改參考品號基本資料 INVMB.MB046 標準進價
		荷拉改廠商代號對應 M030004 (原 M01004), 上線前 XX_SUPPLIERS 需先更新資料
		其餘門市訂單轉移倉單處理
*/

