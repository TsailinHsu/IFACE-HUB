CREATE OR ALTER VIEW COPTG_EIP_ORDER_APPLY_vw 
AS

WITH XX_ORDER AS (
	SELECT
		ID,
		ORDER_ID
	FROM IFACE
		CROSS APPLY
		OPENJSON (JSON_DOC, '$.data') WITH 
			(
				ID				NUMERIC			'$.id',
				ORDER_ID		NVARCHAR(255)	'$.global_order_id'
			)
	WHERE 1=1 
		AND STATUS = '5'
		AND APP_MODULE = N'EIP'
		AND APP_FUNCTION IN (N'super_landing', N'line_gift', N'shopee', N'distributor', N'return_change', N'repost', N'shopify')
)

SELECT ID, CONCAT_WS ( '-', RTRIM (TG001), RTRIM (TG002)) RefId
FROM XX_ORDER
	INNER JOIN SR..COPTG ON TG027 = ORDER_ID
WHERE TG003 < '20260801'	-- 2026/08/01 起回傳改由 integration-hub 執行

UNION ALL

SELECT DISTINCT ID, CONCAT_WS ( '-', RTRIM (TB001), RTRIM (TB002)) RefId
FROM XX_ORDER
	INNER JOIN SR..INVTB ON TB056 = ORDER_ID OR TB043 = ORDER_ID
WHERE TB019 < '20260801'	-- 2026/08/01 起回傳改由 integration-hub 執行
;
