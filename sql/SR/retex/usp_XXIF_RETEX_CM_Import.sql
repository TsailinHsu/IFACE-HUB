	POS 門市訂單轉展店採購單, 不處理 A000 (總倉訂單)

	v1.1 2023/10/13 變更 CREATOR 為 API (原 T0031)

	v1.2 2024/06/26 門市對照表 XX_COUNTERS 新增門市狀態資訊 ACTIVE_CODE 
		'Y'	營業中門市
