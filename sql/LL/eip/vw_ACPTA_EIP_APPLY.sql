CREATE OR ALTER VIEW ACPTA_EIP_APPLY_vw 
AS
WITH XX_APPLY_ID AS (	
SELECT  ID
FROM    IFACE CROSS APPLY OPENJSON(JSON_DOC, '$.data') WITH (ID NUMERIC '$.id')
WHERE   1 = 1 AND STATUS = '5' AND APP_MODULE = N'LLEIP' AND APP_FUNCTION = N'請款單'
)

SELECT  CONCAT_WS('-', RTRIM(TA001), RTRIM(TA002)) RefId, CONVERT(INT, TA087) ID
FROM    LL..ACPTA INNER JOIN  XX_APPLY_ID ON ID = CONVERT(INT, TA087)
WHERE   TA086 = N'EIP'  AND CREATE_DATE = CONVERT(VARCHAR, GETDATE(), 112)
;