CREATE OR ALTER VIEW COPTG_EIP_Requisit_APPLY_vw 
AS

WITH XX_ORDER AS (
	SELECT 
		ID,
		ORDER_ID
	FROM IFACE
		CROSS APPLY
		OPENJSON (JSON_DOC, '$.data') WITH 
			(
				ID				NUMERIC			'$.id',
				ORDER_ID		NVARCHAR(255)	'$.global_order_id'
			)
	WHERE 1=1 
		AND STATUS = '5'
		AND APP_MODULE = N'EIP'
		AND APP_FUNCTION = N'requisit'
)

SELECT ID, CONCAT_WS ( '-', RTRIM (TA001), RTRIM (TA002)) RefId
FROM XX_ORDER
	INNER JOIN SR..INVTA ON TA027 = ORDER_ID
WHERE TA003 < '20260801'	-- 2026/08/01 起回傳改由 integration-hub 執行
;
